CREATE TABLE IF NOT EXISTS users (
 id CHAR(36) PRIMARY KEY, first_name VARCHAR(100) NOT NULL, last_name VARCHAR(100) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL, phone VARCHAR(30) NOT NULL DEFAULT '',
 role ENUM('USER','ADMIN') NOT NULL DEFAULT 'USER', status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
 token_version INT NOT NULL DEFAULT 0, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS refresh_tokens (
 token_hash CHAR(64) PRIMARY KEY, user_id CHAR(36) NOT NULL, expires_at DATETIME NOT NULL,
 revoked BOOLEAN NOT NULL DEFAULT FALSE, token_version INT NOT NULL DEFAULT 0, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id), INDEX(user_id)
);
CREATE TABLE IF NOT EXISTS password_reset_tokens (
 token_hash CHAR(64) PRIMARY KEY, user_id CHAR(36) NOT NULL, expires_at DATETIME NOT NULL,
 used BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id), INDEX(user_id)
);
CREATE TABLE IF NOT EXISTS login_history (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, user_id CHAR(36), email VARCHAR(254) NOT NULL,
 device VARCHAR(500) NOT NULL, login_status VARCHAR(20) NOT NULL,
 login_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP, INDEX(user_id,login_time)
);
CREATE TABLE IF NOT EXISTS rate_limits (
 rate_key CHAR(64) PRIMARY KEY, attempts INT NOT NULL DEFAULT 1, expires_at DATETIME NOT NULL
);
